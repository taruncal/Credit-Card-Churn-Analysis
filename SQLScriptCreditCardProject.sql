CREATE DATABASE credit_card_db;
USE credit_card_db;


CREATE TABLE churn_data (
    Client_Num INT PRIMARY KEY,
    Attrition_Flag VARCHAR(50),
    Customer_Age INT,
    Gender VARCHAR(10),
    Dependent_count INT,
    Education_Level VARCHAR(50),
    Marital_Status VARCHAR(50),
    Income_Category VARCHAR(50),
    Card_Category VARCHAR(50),
    Months_on_book INT,
    Total_Relationship_Count INT,
    Months_Inactive_12_mon INT,
    Contacts_Count_12_mon INT,
    Credit_Limit DECIMAL(10, 2),
    Total_Revolving_Bal DECIMAL(10, 2),
    Avg_Open_To_Buy DECIMAL(10, 2),
    Total_Amt_Chng_Q4_Q1 DECIMAL(6, 4),
    Total_Trans_Amt DECIMAL(10, 2),
    Total_Trans_Ct INT,
    Total_Ct_Chng_Q4_Q1 DECIMAL(6, 4),
    Avg_Utilization_Ratio DECIMAL(6, 4),
    Age_Group VARCHAR(50),
    Tenure_Years DECIMAL(5, 2),
    Avg_Trans_Value DECIMAL(10, 2),
    Utilization_Tier VARCHAR(50)
);





-- 1. Total number of unique accounts in the portfolio
SELECT COUNT(Client_Num) AS Total_Unique_Accounts 
FROM churn_data;








-- 2. Raw count of active versus attrited customers
SELECT Attrition_Flag, COUNT(*) AS Customer_Count 
FROM churn_data 
GROUP BY Attrition_Flag;








-- 3. Exact percentage of customers who have churned across the entire portfolio
SELECT 
    (SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) / COUNT(*)) * 100 AS Exact_Churn_Percentage 
FROM churn_data;







-- 4. Total annual transaction amount generated by all accounts combined
SELECT SUM(Total_Trans_Amt) AS Total_Annual_Transaction_Amount 
FROM churn_data;







-- 5. Mean credit limit extended across the entire customer base
SELECT AVG(Credit_Limit) AS Mean_Credit_Limit 
FROM churn_data;







-- 6. Gender distribution of the customer portfolio
SELECT Gender, COUNT(*) AS Customer_Count, 
       (COUNT(*) * 100.0 / (SELECT COUNT(*) FROM churn_data)) AS Percentage
FROM churn_data
GROUP BY Gender;







-- 7. Average age of customers in the dataset
SELECT AVG(Customer_Age) AS Avg_Customer_Age 
FROM churn_data;










-- 8. Customer distribution across tenure clusters based on months on book
SELECT Months_on_book, COUNT(*) AS Customer_Count 
FROM churn_data 
GROUP BY Months_on_book 
ORDER BY Months_on_book;











-- 9. Customer count per card category (Blue, Silver, Gold, Platinum)
SELECT Card_Category, COUNT(*) AS Customer_Count 
FROM churn_data 
GROUP BY Card_Category;











-- 10. Average revolving balance carried on cards
SELECT AVG(Total_Revolving_Bal) AS Avg_Revolving_Balance 
FROM churn_data;









-- 11. Churn percentage by card category to find which suffers highest attrition
SELECT 
    Card_Category, 
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) AS Churned_Customers,
    (SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)) AS Churn_Rate_Percentage
FROM churn_data 
GROUP BY Card_Category 
ORDER BY Churn_Rate_Percentage DESC;







-- 12. Customer service contact frequency vs. churn rate
SELECT 
    Contacts_Count_12_mon, 
