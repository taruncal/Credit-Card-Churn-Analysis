-- 21. Churn concentration across credit limit deciles using window functions
WITH DecileCTE AS (
    SELECT 
        Client_Num,
        Credit_Limit,
        Attrition_Flag,
        NTILE(10) OVER (ORDER BY Credit_Limit DESC) AS Credit_Decile
    FROM churn_data
)
SELECT 
    Credit_Decile,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) AS Churned_Customers,
    (SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)) AS Churn_Rate_Percentage
FROM DecileCTE
GROUP BY Credit_Decile
ORDER BY Credit_Decile;











-- 22. Corrected query for low-spending outlier accounts
SELECT 
    Client_Num,
    Total_Trans_Amt,
    Attrition_Flag
FROM churn_data
WHERE Total_Trans_Amt < (
    SELECT AVG(Total_Trans_Amt) - (1 * STDDEV(Total_Trans_Amt)) 
    FROM churn_data
);







-- 23. Highest-spending customers inside each card category using DENSE_RANK()
WITH RankedSpendCTE AS (
    SELECT 
        Client_Num,
        Card_Category,
        Total_Trans_Amt,
        DENSE_RANK() OVER (PARTITION BY Card_Category ORDER BY Total_Trans_Amt DESC) AS Spend_Rank
    FROM churn_data
)
SELECT 
    Client_Num,
    Card_Category,
    Total_Trans_Amt,
    Spend_Rank
FROM RankedSpendCTE
WHERE Spend_Rank <= 5;










-- 24. Cumulative transaction volume ordered by total transaction amount
SELECT 
    Client_Num,
    Total_Trans_Amt,
    SUM(Total_Trans_Amt) OVER (ORDER BY Total_Trans_Amt DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS Cumulative_Revenue
FROM churn_data;














-- 25. Churn rate across precise risk tiers categorized by utilization ratios
WITH UtilizationTierCTE AS (
    SELECT 
        Client_Num,
        Attrition_Flag,
        CASE 
            WHEN Avg_Utilization_Ratio = 0 THEN 'Zero Utilization (0%)'
            WHEN Avg_Utilization_Ratio < 0.3 THEN 'Low (0.01 - 0.29)'
            WHEN Avg_Utilization_Ratio < 0.6 THEN 'Moderate (0.30 - 0.59)'
            ELSE 'High (0.60+)'
        END AS Utilization_Tier
    FROM churn_data
)
SELECT 
    Utilization_Tier,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) AS Churned_Customers,
    (SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)) AS Churn_Rate_Percentage
FROM UtilizationTierCTE
GROUP BY Utilization_Tier
ORDER BY Churn_Rate_Percentage DESC;












-- 26. Actual churn count for high-risk profiles meeting multiple friction criteria simultaneously
SELECT 
    COUNT(*) AS High_Risk_Profile_Count,
    SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) AS Actual_Churned_Count
FROM churn_data
WHERE Contacts_Count_12_mon >= 4 
  AND Months_Inactive_12_mon >= 3;
  
  
  
  
  
  
  
  
  
  
-- 27. Corrected Credit Limit Summary Matrix
SELECT 
    Income_Category,
    COALESCE(AVG(CASE WHEN Gender = 'Male' THEN Credit_Limit END), 0) AS Male_Avg_Credit_Limit,
    COALESCE(AVG(CASE WHEN Gender = 'Female' THEN Credit_Limit END), 0) AS Female_Avg_Credit_Limit,
    AVG(Credit_Limit) AS Overall_Avg_Credit_Limit
FROM churn_data
GROUP BY Income_Category
ORDER BY Income_Category;




-- 28. Row numbers assigned to customers ordered by account tenure (Months_on_book) within each income bracket
SELECT 
    Client_Num,
    Income_Category,
    Months_on_book,
    ROW_NUMBER() OVER (PARTITION BY Income_Category ORDER BY Months_on_book DESC) AS Tenure_Row_Num
FROM churn_data;









-- 29. Customers possessing high credit limits ($15,000+) but recording minimal transaction counts (<20)
SELECT 
    Client_Num,
    Credit_Limit,
    Total_Trans_Ct,
    Attrition_Flag
FROM churn_data
WHERE Credit_Limit >= 15000 
  AND Total_Trans_Ct < 20;










-- 30. Comparative churn density across generational age cohorts
WITH AgeCohortCTE AS (
    SELECT 
        Client_Num,
        Attrition_Flag,
        CASE 
            WHEN Customer_Age < 30 THEN 'Under 30 (Gen Z / Young)'
            WHEN Customer_Age BETWEEN 30 AND 49 THEN '30-49 (Millennials / Gen X)'
            WHEN Customer_Age BETWEEN 50 AND 64 THEN '50-64 (Boomers)'
            ELSE '65+ (Silent / Senior)'
        END AS Age_Cohort
    FROM churn_data
)
SELECT 
    Age_Cohort,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) AS Churned_Customers,
    (SUM(CASE WHEN Attrition_Flag = 'Attrited Customer' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)) AS Churn_Rate_Percentage
FROM AgeCohortCTE
GROUP BY Age_Cohort
ORDER BY Churn_Rate_Percentage DESC;


























































