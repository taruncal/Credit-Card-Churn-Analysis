-- 20. Transaction amount change between Q4 and Q1 across churn statuses
SELECT 
    Attrition_Flag, 
    AVG(Total_Amt_Chng_Q4_Q1) AS Avg_Amount_Change_Q4_Q1,
    AVG(Total_Ct_Chng_Q4_Q1) AS Avg_Count_Change_Q4_Q1
FROM churn_data
